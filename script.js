/* =========================================================
   EMAIL VALIDATION
========================================================= */

function isValidEmail(email) {

    return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
}


/* =========================================================
   ZAMBIAN PHONE VALIDATION
========================================================= */

function normalizeZambianPhone(phone) {

    let cleaned =
        String(phone)
            .replace(/\s+/g, "")
            .replace(/-/g, "");


    if (cleaned.startsWith("+260")) {

        return "0" + cleaned.substring(4);

    }


    if (cleaned.startsWith("260")) {

        return "0" + cleaned.substring(3);

    }


    return cleaned;
}


function isValidZambianPhone(phone) {

    const normalized =
        normalizeZambianPhone(phone);

    return /^0\d{9}$/.test(normalized);
}


/* =========================================================
   START MOBILE MONEY PAYMENT
========================================================= */

async function startMobileMoneyPayment(
    product,
    email,
    phone,
    operator
) {

    const normalizedPhone =
        normalizeZambianPhone(phone);


    const reference =
        createPaymentReference(product);


    currentPayment = {

        reference: reference,

        product: product,

        email: email,

        phone: normalizedPhone,

        operator: operator,

        amount: Number(product.price),

        currency: PAYMENT_CURRENCY

    };


    paymentFinalized = false;

    paymentVerificationRunning = false;


    continuePaymentButton.disabled = true;

    continuePaymentButton.textContent =
        "Sending Payment Prompt...";


    paymentModal.classList.add("hidden");

    restoreBodyScroll();


    showNotification(
        "Sending Payment Prompt",
        "We are sending a payment request to your mobile phone. Please wait.",
        "..."
    );


    try {

        const response =
            await fetch(
                INITIATE_ENDPOINT,
                {

                    method: "POST",

                    headers: {
                        "Content-Type":
                            "application/json",

                        "Accept":
                            "application/json"
                    },

                    body: JSON.stringify({

                        reference: reference,

                        amount:
                            Number(product.price),

                        currency:
                            PAYMENT_CURRENCY,

                        email: email,

                        phone:
                            normalizedPhone,

                        operator: operator,

                        country: "zm"

                    }),

                    cache: "no-store"

                }
            );


        const result =
            await response.json();


        console.log(
            "Payment initiation response:",
            result
        );


        if (
            !response.ok ||
            !result.success
        ) {

            resetPaymentButton();

            currentPayment = null;


            showNotification(
                "Payment Could Not Start",
                result.message ||
                    "Could not start the mobile-money payment.",
                "!"
            );

            return;
        }


        const payment =
            result.payment;


        currentPayment.reference =
            payment.reference ||
            reference;


        closeNotification();


        showNotification(
            "Approve Payment",
            "DO NOT REFRESH THIS PAGE until payment is confirmed.",
            "!"
        );


        beginPaymentVerification(
            currentPayment.reference
        );

    } catch (error) {

        console.error(
            "Payment initiation error:",
            error
        );


        resetPaymentButton();

        currentPayment = null;


        showNotification(
            "Connection Error",
            "We could not connect to the payment service. Please check your internet connection and try again.",
            "!"
        );
    }
}


/* =========================================================
   CREATE REFERENCE
========================================================= */

function createPaymentReference(product) {

    const timestamp =
        Date.now();


    const randomPart =
        Math.random()
            .toString(36)
            .substring(2, 9);


    return (
        "bakulu-" +
        product.productNumber +
        "-" +
        timestamp +
        "-" +
        randomPart
    );
}


/* =========================================================
   VERIFY PAYMENT
========================================================= */

function beginPaymentVerification(reference) {

    if (
        paymentFinalized ||
        !currentPayment ||
        paymentVerificationRunning
    ) {

        return;
    }


    paymentVerificationRunning = true;

    clearVerificationTimer();

    verificationAttempts = 0;


    checkPaymentStatus(reference);
}


async function checkPaymentStatus(reference) {

    if (
        paymentFinalized ||
        !currentPayment
    ) {

        return;
    }


    verificationAttempts++;


    console.log(
        "Checking payment:",
        reference
    );


    console.log(
        "Verification attempt:",
        verificationAttempts
    );


    try {

        const url =
            VERIFY_ENDPOINT +
            "?reference=" +
            encodeURIComponent(reference) +
            "&amount=" +
            encodeURIComponent(
                currentPayment.amount
            ) +
            "&currency=" +
            encodeURIComponent(
                currentPayment.currency
            );


        const response =
            await fetch(
                url,
                {

                    method: "GET",

                    headers: {
                        "Accept":
                            "application/json"
                    },

                    cache: "no-store"

                }
            );


        const responseText =
            await response.text();


        console.log(
            "Verification HTTP status:",
            response.status
        );


        console.log(
            "Verification response:",
            responseText
        );


        let result = null;


        try {

            result =
                JSON.parse(responseText);

        } catch {

            console.error(
                "Invalid verification JSON."
            );

        }


        /* SUCCESS */

        if (
            response.ok &&
            result &&
            result.success === true &&
            result.payment &&
            String(
                result.payment.status
            ).toLowerCase() ===
                "successful"
        ) {

            finalizeSuccessfulPayment(
                result.payment
            );

            return;
        }


        /* FAILED */

        if (
            result &&
            (
                result.status === "failed" ||
                result.status === "cancelled"
            )
        ) {

            handleFailedPayment(
                result.message
            );

            return;
        }


        /* KEEP CHECKING */

        if (
            verificationAttempts <
            MAX_VERIFICATION_ATTEMPTS
        ) {

            scheduleNextVerification(
                reference
            );

            return;
        }


        showPaymentStillChecking();

    } catch (error) {

        console.error(
            "Verification error:",
            error
        );


        if (
            verificationAttempts <
            MAX_VERIFICATION_ATTEMPTS
        ) {

            scheduleNextVerification(
                reference
            );

            return;
        }


        showPaymentStillChecking();
    }
}


/* =========================================================
   NEXT VERIFICATION
========================================================= */

function scheduleNextVerification(reference) {

    clearVerificationTimer();


    verificationTimer =
        setTimeout(
            function () {

                checkPaymentStatus(
                    reference
                );

            },
            VERIFICATION_INTERVAL
        );
}


/* =========================================================
   SUCCESS
========================================================= */

function finalizeSuccessfulPayment(payment) {

    if (
        paymentFinalized ||
        !currentPayment
    ) {

        return;
    }


    paymentFinalized = true;

    paymentVerificationRunning = false;

    clearVerificationTimer();

    resetPaymentButton();


    const product =
        currentPayment.product;


    const reference =
        payment.reference ||
        currentPayment.reference;


    console.log(
        "PAYMENT SUCCESSFULLY VERIFIED:",
        payment
    );


    closeNotification();


    showPurchaseSummary(
        product,
        reference
    );


    currentPayment = null;
}


