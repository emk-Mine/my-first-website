/* =========================================================
   CLOSE PURCHASE SUMMARY
========================================================= */

function closePurchaseSummary() {

    if (!summarySection) {
        return;
    }


    summarySection.classList.add(
        "hidden"
    );


    restoreBodyScroll();
}


/* =========================================================
   CALL PRODUCT
========================================================= */

function callProduct(phone) {

    window.location.href =
        "tel:" + phone;
}


/* =========================================================
   FEATURE LINK
========================================================= */

function openProductLink(link) {

    try {

        const url =
            new URL(link);


        if (
            url.protocol !== "https:" &&
            url.protocol !== "http:"
        ) {

            throw new Error(
                "Invalid URL"
            );
        }


        window.location.href =
            url.href;

    } catch {

        showNotification(
            "Link Error",
            "This feature link is not available.",
            "!"
        );
    }
}


/* =========================================================
   FORMAT AMOUNT
========================================================= */

function formatAmount(amount) {

    const number =
        Number(amount);


    if (Number.isNaN(number)) {
        return "0";
    }


    return number
        .toFixed(2)
        .replace(/\.00$/, "");
}


/* =========================================================
   ESCAPE HTML
========================================================= */

function escapeHtml(value) {

    return String(value)

        .replace(/&/g, "&amp;")

        .replace(/</g, "&lt;")

        .replace(/>/g, "&gt;")

        .replace(/"/g, "&quot;")

        .replace(/'/g, "&#039;");
}


/* =========================================================
   RESTORE BODY SCROLL
========================================================= */

function restoreBodyScroll() {

    const paymentOpen =
        paymentModal &&
        !paymentModal.classList.contains(
            "hidden"
        );


    const notificationOpen =
        notificationModal &&
        !notificationModal.classList.contains(
            "hidden"
        );


    const summaryOpen =
        summarySection &&
        !summarySection.classList.contains(
            "hidden"
        );


    const imagePreview =
        document.getElementById(
            "imagePreview"
        );


    const previewOpen =
        imagePreview &&
        !imagePreview.classList.contains(
            "hidden"
        );


    if (
        paymentOpen ||
        notificationOpen ||
        summaryOpen ||
        previewOpen
    ) {

        document.body.style.overflow =
            "hidden";

    } else {

        document.body.style.overflow =
            "";
    }
}


