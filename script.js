// EPORNER VIDEO ROLLS
// ==========================================

let epornerPage = 1;
const epornerPerPage = 50;

let epornerLoading = false;
let epornerFinished = false;

async function loadEpornerVideos() {

    const containers = [
        document.getElementById("videoContainer1"),
        document.getElementById("videoContainer2"),
        document.getElementById("videoContainer3")
    ];

    const loadMoreButton =
        document.getElementById("loadMoreVideos");

    if (!containers[0]) {
        return;
    }

    if (epornerLoading || epornerFinished) {
        return;
    }

    epornerLoading = true;

    if (loadMoreButton) {
        loadMoreButton.textContent = "Loading videos...";
        loadMoreButton.disabled = true;
    }

    try {

        const apiUrl =
            "https://www.eporner.com/api/v2/video/search/" +
            "?query=all" +
            "&per_page=" + epornerPerPage +
            "&page=" + epornerPage +
            "&thumbsize=big" +
            "&order=latest" +
            "&format=json";

        const response =
            await fetch(apiUrl);

        if (!response.ok) {
            throw new Error(
                "Eporner returned HTTP " +
                response.status
            );
        }

        const data =
            await response.json();

        const videos =
            Array.isArray(data.videos)
                ? data.videos
                : [];

        if (videos.length === 0) {

            epornerFinished = true;

            if (loadMoreButton) {
                loadMoreButton.textContent =
                    "No more videos";

                loadMoreButton.disabled = true;
            }

            return;
        }

        // Shuffle this batch
        for (
            let i = videos.length - 1;
            i > 0;
            i--
        ) {

            const j =
                Math.floor(
                    Math.random() * (i + 1)
                );

            [
                videos[i],
                videos[j]
            ] = [
                videos[j],
                videos[i]
            ];
        }

        videos.forEach(function(video, index) {

            const videoId =
                video.id || "";

            const title =
                video.title ||
                "Untitled Video";

            const image =
                video.image ||
                video.default_thumb?.src ||
                video.thumb ||
                video.thumbnail ||
                video.thumb_url ||
                video.thumbnail_url ||
                video.poster ||
                "";

            const duration =
                video.length_min ||
                "";

            if (!videoId) {
                return;
            }

            const card =
                document.createElement("div");

            card.className =
                "video-card";

            card.innerHTML = `

                <div
                    class="video-thumbnail"
                    onclick="openEpornerVideo('${videoId}')"
                >

                    <img
                        src="${image}"
                        alt="${escapeHtml(title)}"
                        loading="lazy"
                        onerror="this.style.display='none';"
                    >

                    <div class="video-play">
                        ▶
                    </div>

                </div>

                <div class="video-info">

                    <h3>
                        ${escapeHtml(title)}
                    </h3>

                    ${
                        duration
                        ? `
                            <span class="video-duration">
                                ${escapeHtml(duration)}
                            </span>
                        `
                        : ""
                    }

                    <button
                        type="button"
                        class="video-button"
                        onclick="openEpornerVideo('${videoId}')"
                    >
                        Watch Video
                    </button>

                </div>
            `;

            // Distribute videos across 3 rolls
            const rollIndex =
                index % 3;

            containers[rollIndex]
                .appendChild(card);

        });

        epornerPage++;

        if (videos.length < epornerPerPage) {

            epornerFinished = true;

            if (loadMoreButton) {

                loadMoreButton.textContent =
                    "No more videos";

                loadMoreButton.disabled = true;
            }

        } else {

            if (loadMoreButton) {

                loadMoreButton.textContent =
                    "Load More Videos";

                loadMoreButton.disabled = false;
            }
        }

    } catch (error) {

        console.error(
            "Eporner videos failed:",
            error
        );

        if (loadMoreButton) {

            loadMoreButton.textContent =
                "Try Again";

            loadMoreButton.disabled =
                false;
        }

    } finally {

        epornerLoading = false;
    }
}

