/* =========================================================
   FORMAT AMOUNT
========================================================= */

function formatAmount(amount) {

    const number =
        Number(amount);


    if (Number.isNaN(number)) {
        return "0";
    }


    return number
        .toFixed(2)
        .replace(/\.00$/, "");
}


/* =========================================================
   ESCAPE HTML
========================================================= */

function escapeHtml(value) {

    return String(value)

        .replace(/&/g, "&amp;")

        .replace(/</g, "&lt;")

        .replace(/>/g, "&gt;")

        .replace(/"/g, "&quot;")

        .replace(/'/g, "&#039;");
}


