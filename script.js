// ==========================================
// PERFORM SEARCH
// ==========================================

function performSearch() {

    if (!searchInput || !searchResults) {
        return;
    }


    const searchTerm =
        searchInput.value
            .trim()
            .toLowerCase();


    // ======================================
    // EMPTY SEARCH
    // ======================================

    if (!searchTerm) {

        searchResults.innerHTML = `
            <div class="search-no-results">
                Start typing to search.
            </div>
        `;

        return;

    }


    // ======================================
    // FIND MATCHES
    // ======================================

    const results =
        searchableProducts.filter(
            (product) => {

                const searchableText = [

                    product.productNumber || "",

                    product.name || "",

                    product.description || "",

                    product.location || "",

                    product.price || "",

                    product.searchCategory || ""

                ]
                    .join(" ")
                    .toLowerCase();


                return searchableText.includes(
                    searchTerm
                );

            }
        );


    // ======================================
    // NO RESULTS
    // ======================================

    if (results.length === 0) {

        searchResults.innerHTML = `
            <div class="search-no-results">
                No results found for
                "${escapeHtml(searchInput.value)}".
            </div>
        `;

        return;

    }


    // ======================================
    // DISPLAY RESULTS
    // ======================================

    searchResults.innerHTML =
        results
            .map(
                (product, index) => {

                    return `

                        <div
                            class="search-result"
                            data-search-index="${index}"
                        >

                            <img
                                class="search-result-image"
                                src="${product.image}"
                                alt="${escapeHtml(product.name || "")}"
                                loading="lazy"
                            >

                            <div class="search-result-info">

                                <div class="search-result-name">

                                    ${escapeHtml(
                                        product.name || ""
                                    )}

                                </div>


                                <div class="search-result-details">

                                    ${escapeHtml(
                                        product.searchCategory || ""
                                    )}

                                    •

                                    ${escapeHtml(
                                        product.location || ""
                                    )}

                                </div>

                            </div>


                            <div class="search-result-price">

                                K${formatAmount(
                                    product.price
                                )}

                            </div>

                        </div>

                    `;

                }
            )
            .join("");


    // ======================================
    // CLICK SEARCH RESULT
    // ======================================

    const resultCards =
        searchResults.querySelectorAll(
            ".search-result"
        );


    resultCards.forEach(
        (card) => {

            card.addEventListener(
                "click",
                () => {

                    const index =
                        Number(
                            card.dataset.searchIndex
                        );


                    const product =
                        results[index];


                    if (!product) {
                        return;
                    }


                    closeSearch();


                    openPaymentModal(
                        product
                    );

                }
            );

        }
    );

}


